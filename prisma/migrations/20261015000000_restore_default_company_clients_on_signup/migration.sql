-- Restore the approved demo Client bootstrap that was superseded when the
-- workspace provisioner was rebuilt for the final role-permission foundation.
-- This changes no table shape: rows are inserted only inside the existing
-- SECURITY DEFINER company-workspace transaction, after the tenant/company
-- pair exists and before its result is returned to the caller.
--
-- Rollback: recreate the immediately preceding provision_company_workspace_core
-- definition. Do not delete provisioned Client or ClientContact rows: they are
-- ordinary, editable business data once the workspace has been created.

DO $migration$
DECLARE
  v_definition text;
  v_marker text := $old$
  PERFORM public.reconcile_tenant_starter_roles(v_tenant_id);
  RETURN QUERY SELECT v_tenant_id, v_company_id, v_user_id, v_user_role_id, v_actor_profile_id;$old$;
  v_replacement text := $new$
  PERFORM public.reconcile_tenant_starter_roles(v_tenant_id);

  -- UUID v4 values are generated by PostgreSQL for every Client and contact;
  -- they are independent of client-provided identifiers and collision-safe.
  WITH default_clients (id, name, contact_name, contact_email, contact_designation) AS (
    VALUES
      (gen_random_uuid(), 'Bluewater Marine Logistics', 'Nadia Rahman', 'nadia.rahman@bluewater-marine.test', 'Commercial Manager'),
      (gen_random_uuid(), 'Meridian Offshore Services', 'Arif Hossain', 'arif.hossain@meridian-offshore.test', 'Operations Director'),
      (gen_random_uuid(), 'Seaport Engineering Partners', 'Farzana Islam', 'farzana.islam@seaport-engineering.test', 'Project Controls Lead')
  ),
  inserted_clients AS (
    INSERT INTO public.clients (tenant_id, id, company_id, name, is_active)
    SELECT v_tenant_id, default_client.id, v_company_id, default_client.name, true
    FROM default_clients AS default_client
    RETURNING id
  )
  INSERT INTO public.client_contacts (
    tenant_id, id, client_id, name, email, designation, is_primary, is_active
  )
  SELECT
    v_tenant_id,
    gen_random_uuid(),
    default_client.id,
    default_client.contact_name,
    default_client.contact_email,
    default_client.contact_designation,
    true,
    true
  FROM default_clients AS default_client
  JOIN inserted_clients ON inserted_clients.id = default_client.id;

  RETURN QUERY SELECT v_tenant_id, v_company_id, v_user_id, v_user_role_id, v_actor_profile_id;$new$;
BEGIN
  SELECT pg_get_functiondef(
    'public.provision_company_workspace_core(text, text, uuid, text, text, text, text, text)'::regprocedure
  ) INTO v_definition;

  IF position(v_marker IN v_definition) = 0 THEN
    RAISE EXCEPTION 'Cannot restore default Clients: expected final starter-role reconciliation and return were not found in provision_company_workspace_core'
      USING ERRCODE = '55000';
  END IF;

  -- Replace exactly one terminal marker. The stored function keeps its existing
  -- owner, SECURITY DEFINER setting, search_path, and revoke/grant posture.
  v_definition := replace(v_definition, v_marker, v_replacement);
  EXECUTE v_definition;
END;
$migration$;

REVOKE ALL ON FUNCTION public.provision_company_workspace_core(text, text, uuid, text, text, text, text, text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.provision_company_workspace_core(text, text, uuid, text, text, text, text, text) FROM app_user;
